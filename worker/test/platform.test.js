import { describe, it, expect } from 'vitest';
import { env, createExecutionContext, waitOnExecutionContext } from 'cloudflare:test';
import worker from '../src/index.js';
import { Client } from './helpers.js';
import { CSP, configProblem } from '../src/security.js';

async function get(path, init) {
    const ctx = createExecutionContext();
    const res = await worker.fetch(new Request('http://localhost:8787' + path, init), env, ctx);
    await waitOnExecutionContext(ctx);
    return res;
}

describe('API basics', () => {
    it('GET /api/health', async () => {
        const res = await get('/api/health');
        expect(res.status).toBe(200);
        expect(await res.json()).toEqual({ status: 'ok', version: 'dev' });
        expect(res.headers.get('Cache-Control')).toBe('no-store');
    });

    it('GET /api/config exposes only the public Turnstile site key', async () => {
        const res = await get('/api/config');
        expect(await res.json()).toEqual({ turnstileSiteKey: '1x00000000000000000000AA' });
    });

    it('unknown API routes and unlisted auth routes answer 404 with the uniform error shape', async () => {
        for (const path of ['/api/nothing', '/api/auth/list-sessions', '/api/auth/two-factor/get-totp-uri']) {
            const res = await get(path);
            expect(res.status, path).toBe(404);
            expect(await res.json()).toEqual({ error: 'not_found', message: 'Not found.' });
        }
    });

    it('API responses carry the security headers', async () => {
        const res = await get('/api/health');
        expect(res.headers.get('X-Content-Type-Options')).toBe('nosniff');
        expect(res.headers.get('Strict-Transport-Security')).toContain('max-age=');
    });
});

describe('static assets and security headers', () => {
    it('serves index.html with CSP, HSTS, nosniff, referrer and permissions policy', async () => {
        const res = await get('/');
        expect(res.status).toBe(200);
        expect(res.headers.get('Content-Type')).toContain('text/html');
        expect(res.headers.get('Content-Security-Policy')).toBe(CSP);
        expect(res.headers.get('Strict-Transport-Security')).toBe('max-age=31536000; includeSubDomains');
        expect(res.headers.get('X-Content-Type-Options')).toBe('nosniff');
        expect(res.headers.get('Referrer-Policy')).toBe('strict-origin-when-cross-origin');
        expect(res.headers.get('Permissions-Policy')).toBe('bluetooth=(self)');
        expect(res.headers.get('X-Frame-Options')).toBe('DENY');
        const html = await res.text();
        expect(html).toMatch(/src="app\.js\?v=/); // cache busting applied by the build
    });

    it('the CSP contains exactly the required directives', () => {
        const directives = Object.fromEntries(CSP.split('; ').map((d) => [d.split(' ')[0], d.split(' ').slice(1)]));
        expect(directives['script-src']).toEqual(expect.arrayContaining(["'self'", "'unsafe-inline'", "'unsafe-eval'", 'https://unpkg.com', 'https://cdn.jsdelivr.net', 'https://challenges.cloudflare.com']));
        expect(directives['connect-src']).toEqual(["'self'", 'wss://zwift-signaling.w-vollprecht.workers.dev']);
        expect(directives['frame-src']).toEqual(['https://challenges.cloudflare.com']);
        expect(directives['object-src']).toEqual(["'none'"]);
        expect(directives['frame-ancestors']).toEqual(["'none'"]);
        expect(directives['base-uri']).toEqual(["'self'"]);
        expect(directives['default-src']).toEqual(["'self'"]);
    });

    it('non-HTML assets get nosniff and HSTS but no CSP', async () => {
        const res = await get('/app.js');
        expect(res.status).toBe(200);
        expect(res.headers.get('X-Content-Type-Options')).toBe('nosniff');
        expect(res.headers.get('Content-Security-Policy')).toBeNull();
    });

    it('version.js is generated by the build', async () => {
        const text = await (await get('/version.js')).text();
        expect(text).toContain('window.APP_VERSION');
        expect(text).toContain('cacheBuster');
    });

    it('does not serve repo files that are not on the allowlist', async () => {
        for (const path of ['/README.md', '/index.html.bak', '/tests/reliability.test.cjs', '/worker/package.json', '/docs/api.md', '/.git/config', '/session.js', '/setup-git.sh']) {
            const res = await get(path);
            // the asset layer answers 404 (or falls back to index.html for SPA-less 404 handling); never file content
            const body = await res.text();
            expect(body, path).not.toContain('cadence-worker');
            expect(body, path).not.toContain('Cadence API contract');
            expect(res.status === 404 || res.headers.get('Content-Type')?.includes('text/html'), path).toBe(true);
        }
    });
});

describe('configuration guard', () => {
    it('reports problems instead of running with unsafe settings', () => {
        const ok = { BETTER_AUTH_SECRET: 'x'.repeat(32), BASE_URL: 'https://cadence.example', EMAIL_MODE: 'resend', RESEND_API_KEY: 'k', TURNSTILE_SECRET_KEY: 's' };
        expect(configProblem(ok)).toBeNull();
        expect(configProblem({ ...ok, BETTER_AUTH_SECRET: 'short' })).toMatch(/BETTER_AUTH_SECRET/);
        expect(configProblem({ ...ok, EMAIL_MODE: 'console' })).toMatch(/console/);
        expect(configProblem({ ...ok, BASE_URL: 'http://cadence.example' })).toMatch(/https/);
        expect(configProblem({ ...ok, RESEND_API_KEY: '' })).toMatch(/RESEND/);
        expect(configProblem({ ...ok, TURNSTILE_SECRET_KEY: '' })).toMatch(/TURNSTILE/);
        expect(configProblem({ ...ok, BASE_URL: 'http://localhost:8787', EMAIL_MODE: 'console' })).toBeNull();
    });

    it('rejects an Origin that is not BASE_URL or TRUSTED_ORIGINS, accepts a trusted one', async () => {
        const client = new Client({ TRUSTED_ORIGINS: 'https://staging.example.com, http://127.0.0.1:8787' });
        const trusted = await client.json('/api/rides', { method: 'POST', body: {}, origin: 'http://127.0.0.1:8787' });
        expect(trusted.status).toBe(401); // got past the Origin check, stopped by authentication
        const foreign = await client.json('/api/rides', { method: 'POST', body: {}, origin: 'http://127.0.0.1:9999' });
        expect(foreign.status).toBe(403);
    });
});

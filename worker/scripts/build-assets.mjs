// Copies an explicit ALLOWLIST of frontend files from the repo root into worker/dist/ (the Worker's static assets),
// regenerates version.js and adds ?v=<hash> cache busting, like .github/workflows/deploy.yml does for GitHub Pages.
// The repo root itself is never served: anything not listed here (tests, docs, .bak files, screenshots,
// cloudflare-signaling/, worker/ ...) cannot leak into the deployment.

import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..', '..');
const dist = resolve(here, '..', 'dist');

// Always present. Build fails when one is missing.
const REQUIRED_FILES = [
    'index.html',
    'style.css',
    'favicon.svg',
    'debug.html',
    'version.js',
    'alpine-store.js',
    'ftms.js',
    'chart.js',
    'workout-preview.js',
    'workout-progress.js',
    'workout-recorder.js',
    'workout-designer.js',
    'hr-zones.js',
    'session-p2p.js',
    'racetrack.js',
    'zwo-converter.js',
    'app.js'
];
// Added by the accounts feature: copied only if they exist (an index.html that references one must find it, see below).
const OPTIONAL_FILES = ['account.js', 'history.js'];
const DIRECTORIES = ['sample-workouts'];

function git(args) {
    try {
        return execFileSync('git', args, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
    } catch {
        return '';
    }
}

const hashFull = process.env.GIT_SHA || git(['rev-parse', 'HEAD']) || 'dev';
const hash = hashFull === 'dev' ? 'dev' : hashFull.slice(0, 7);
const timestamp = new Date().toISOString();

rmSync(dist, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });

const files = [...REQUIRED_FILES];
for (const name of OPTIONAL_FILES) if (existsSync(join(root, name))) files.push(name);

for (const name of files) {
    const source = join(root, name);
    if (!existsSync(source)) throw new Error(`build-assets: required file missing: ${name}`);
    if (name === 'version.js') continue; // generated below
    cpSync(source, join(dist, name));
}
for (const dir of DIRECTORIES) cpSync(join(root, dir), join(dist, dir), { recursive: true });

// version.js (same shape as the one deploy.yml writes)
writeFileSync(
    join(dist, 'version.js'),
    `// Auto-generated by worker/scripts/build-assets.mjs
window.APP_VERSION = {
    gitHash: '${hash}',
    gitHashFull: '${hashFull}',
    timestamp: '${timestamp}',
    cacheBuster: '${hash}'
};

// Update version display if element exists
document.addEventListener('DOMContentLoaded', function() {
    if (document.getElementById('gitHash')) {
        document.getElementById('gitHash').textContent = 'v${hash}';
    }
});
`
);

// Cache busting for local assets in index.html, exactly the two substitutions deploy.yml performs.
const indexPath = join(dist, 'index.html');
let html = readFileSync(indexPath, 'utf8');

// Guard: every local script / stylesheet referenced by index.html must be in the allowlist and present in dist/.
const referenced = [
    ...[...html.matchAll(/<script[^>]*\ssrc="([^":?#]+)"/g)].map((m) => m[1]),
    ...[...html.matchAll(/<link[^>]*\shref="([^":?#]+\.css)"/g)].map((m) => m[1])
];
for (const ref of referenced) {
    if (!existsSync(join(dist, ref))) {
        throw new Error(`build-assets: index.html references "${ref}", which is not in the allowlist or does not exist. Add it to scripts/build-assets.mjs.`);
    }
}

html = html.replace(/href="style\.css"/g, `href="style.css?v=${hash}"`);
html = html.replace(/src="([^":]*\.js)"/g, `src="$1?v=${hash}"`);
writeFileSync(indexPath, html);

console.log(`build-assets: ${files.length} files + ${DIRECTORIES.join(', ')} -> worker/dist (version ${hash})`);
